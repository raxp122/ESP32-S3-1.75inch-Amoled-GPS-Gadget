const char *T(int id)
{
    if (id < 0 || id >= S_COUNT) return "";
    const char *s = tab[id][g_set.lang < LANG_COUNT ? g_set.lang : 0];
    return s ? s : tab[id][LANG_EN] ? tab[id][LANG_EN] : "";
}

const char *i18n_lang_name(int l) { return l == LANG_EN ? "English" : "Italiano"; }

